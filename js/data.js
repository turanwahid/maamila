  [...list].sort((x, y) => {
    const cx = /^شهر /.test(x) ? 0 : 1,
      cy = /^شهر /.test(y) ? 0 : 1;
    return cx - cy || (cx === 0 ? 0 : x.localeCompare(y, 'fa'));
  });
